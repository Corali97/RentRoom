-- RentRoom Semana 9: exclusividad de reservas y validación de fechas.
-- Ejecutar como propietario del esquema después de migrate_s8.sql.
-- No elimina tablas ni datos. El API confirma o revierte la transacción.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
CREATE OR REPLACE PROCEDURE SP_CREAR_RESERVA (
 P_ID_PRODUCTO IN NUMBER, P_ID_CLIENTE IN NUMBER,
 P_FECHA_INICIO IN DATE, P_FECHA_FIN IN DATE, P_ID_RESERVA OUT NUMBER
) AS
 V_ESTADO PRODUCTO.ESTADO%TYPE;
 V_PROPIETARIO PRODUCTO.ID_PROPIETARIO%TYPE;
 V_OCUPADAS NUMBER;
BEGIN
 IF P_FECHA_INICIO IS NULL OR P_FECHA_FIN IS NULL OR
    TRUNC(P_FECHA_INICIO)<TRUNC(SYSDATE) OR TRUNC(P_FECHA_FIN)<TRUNC(P_FECHA_INICIO) THEN
    RAISE_APPLICATION_ERROR(-20101,'Fechas invalidas.'); END IF;
 SELECT ESTADO, ID_PROPIETARIO INTO V_ESTADO,V_PROPIETARIO
 FROM PRODUCTO WHERE ID_PRODUCTO=P_ID_PRODUCTO FOR UPDATE;
 IF V_ESTADO<>'DISPONIBLE' THEN RAISE_APPLICATION_ERROR(-20102,'Producto no disponible.'); END IF;
 IF V_PROPIETARIO=P_ID_CLIENTE THEN RAISE_APPLICATION_ERROR(-20103,'No puedes reservar tu producto.'); END IF;
 SELECT COUNT(*) INTO V_OCUPADAS FROM RESERVA
 WHERE ID_PRODUCTO=P_ID_PRODUCTO AND ESTADO IN ('PENDIENTE','CONFIRMADA')
   AND FECHA_INICIO<=TRUNC(P_FECHA_FIN) AND FECHA_FIN>=TRUNC(P_FECHA_INICIO);
 IF V_OCUPADAS>0 THEN RAISE_APPLICATION_ERROR(-20104,'Fechas ocupadas.'); END IF;
 INSERT INTO RESERVA(ID_PRODUCTO,ID_ARRENDATARIO,FECHA_INICIO,FECHA_FIN,ESTADO)
 VALUES(P_ID_PRODUCTO,P_ID_CLIENTE,TRUNC(P_FECHA_INICIO),TRUNC(P_FECHA_FIN),'PENDIENTE')
 RETURNING ID_RESERVA INTO P_ID_RESERVA;
EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20105,'Producto inexistente.');
END;
/
CREATE OR REPLACE PROCEDURE SP_CANCELAR_RESERVA(P_ID_RESERVA IN NUMBER,P_ID_CLIENTE IN NUMBER) AS
 V_PRODUCTO NUMBER; V_ESTADO RESERVA.ESTADO%TYPE; V_LOCK NUMBER;
BEGIN
 SELECT ID_PRODUCTO INTO V_PRODUCTO FROM RESERVA WHERE ID_RESERVA=P_ID_RESERVA;
 SELECT ID_PRODUCTO INTO V_LOCK FROM PRODUCTO WHERE ID_PRODUCTO=V_PRODUCTO FOR UPDATE;
 SELECT ESTADO INTO V_ESTADO FROM RESERVA
 WHERE ID_RESERVA=P_ID_RESERVA AND ID_ARRENDATARIO=P_ID_CLIENTE FOR UPDATE;
 IF V_ESTADO NOT IN ('PENDIENTE','CONFIRMADA') THEN RAISE_APPLICATION_ERROR(-20106,'Reserva no cancelable.'); END IF;
 UPDATE RESERVA SET ESTADO='CANCELADA' WHERE ID_RESERVA=P_ID_RESERVA;
EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20107,'Reserva ajena o inexistente.');
END;
/
CREATE OR REPLACE PROCEDURE SP_CONFIRMAR_RESERVA(P_ID_RESERVA IN NUMBER,P_ID_PROPIETARIO IN NUMBER) AS
 V_PRODUCTO NUMBER; V_PROPIETARIO NUMBER; V_ESTADO RESERVA.ESTADO%TYPE;
BEGIN
 SELECT ID_PRODUCTO INTO V_PRODUCTO FROM RESERVA WHERE ID_RESERVA=P_ID_RESERVA;
 SELECT ID_PROPIETARIO INTO V_PROPIETARIO FROM PRODUCTO WHERE ID_PRODUCTO=V_PRODUCTO FOR UPDATE;
 IF V_PROPIETARIO<>P_ID_PROPIETARIO THEN RAISE_APPLICATION_ERROR(-20108,'Reserva ajena.'); END IF;
 SELECT ESTADO INTO V_ESTADO FROM RESERVA WHERE ID_RESERVA=P_ID_RESERVA FOR UPDATE;
 IF V_ESTADO<>'PENDIENTE' THEN RAISE_APPLICATION_ERROR(-20109,'Reserva no pendiente.'); END IF;
 UPDATE RESERVA SET ESTADO='CONFIRMADA' WHERE ID_RESERVA=P_ID_RESERVA;
EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20110,'Reserva inexistente.');
END;
/
SELECT OBJECT_NAME,STATUS FROM USER_OBJECTS WHERE OBJECT_NAME IN
 ('SP_CREAR_RESERVA','SP_CANCELAR_RESERVA','SP_CONFIRMAR_RESERVA');
