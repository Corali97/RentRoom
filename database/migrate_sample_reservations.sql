-- Catalogo de muestra y reservas persistentes para RentRoom.
-- Ejecutar como propietario del esquema RENTROOM_S5_EVIDENCE en XEPDB1.
-- Puede repetirse: crea tablas faltantes y actualiza los dos registros de muestra.
SET SERVEROUTPUT ON
WHENEVER OSERROR EXIT FAILURE ROLLBACK
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
  current_schema VARCHAR2(128) := SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');
  container_name VARCHAR2(128) := SYS_CONTEXT('USERENV', 'CON_NAME');
BEGIN
  IF current_schema <> 'RENTROOM_S5_EVIDENCE' OR container_name <> 'XEPDB1' THEN
    RAISE_APPLICATION_ERROR(-20010, 'Seleccionar XEPDB1 y CURRENT_SCHEMA=RENTROOM_S5_EVIDENCE.');
  END IF;

  BEGIN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE PRENDA_MUESTRA (
        CODIGO_PRENDA VARCHAR2(40) PRIMARY KEY,
        NOMBRE VARCHAR2(120) NOT NULL,
        DESCRIPCION VARCHAR2(500) NOT NULL,
        CATEGORIA VARCHAR2(80) NOT NULL,
        TALLA VARCHAR2(10) NOT NULL,
        GENERO VARCHAR2(20) NOT NULL,
        PRECIO_DIA NUMBER(10,2) NOT NULL,
        GARANTIA NUMBER(10,2) NOT NULL,
        ESTADO VARCHAR2(10) DEFAULT 'ACTIVA' NOT NULL,
        CONSTRAINT CK_MUESTRA_PRECIO CHECK (PRECIO_DIA > 0),
        CONSTRAINT CK_MUESTRA_GARANTIA CHECK (GARANTIA >= 0),
        CONSTRAINT CK_MUESTRA_ESTADO CHECK (ESTADO IN ('ACTIVA','INACTIVA'))
      )
    ]';
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE <> -955 THEN RAISE; END IF;
  END;

  BEGIN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE RESERVA_MUESTRA (
        ID_RESERVA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        CODIGO_PRENDA VARCHAR2(40) NOT NULL,
        ID_ARRENDATARIO NUMBER NOT NULL,
        FECHA_INICIO DATE NOT NULL,
        FECHA_FIN DATE NOT NULL,
        PRECIO_DIA NUMBER(10,2) NOT NULL,
        GARANTIA NUMBER(10,2) NOT NULL,
        ESTADO VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
        FECHA_CREACION DATE DEFAULT SYSDATE NOT NULL,
        CONSTRAINT FK_MUESTRA_RES_PRENDA FOREIGN KEY (CODIGO_PRENDA)
          REFERENCES PRENDA_MUESTRA(CODIGO_PRENDA),
        CONSTRAINT FK_MUESTRA_RES_USUARIO FOREIGN KEY (ID_ARRENDATARIO)
          REFERENCES USUARIO(ID_USUARIO),
        CONSTRAINT CK_MUESTRA_RES_FECHAS CHECK (FECHA_FIN >= FECHA_INICIO),
        CONSTRAINT CK_MUESTRA_RES_PRECIO CHECK (PRECIO_DIA > 0),
        CONSTRAINT CK_MUESTRA_RES_GARANTIA CHECK (GARANTIA >= 0),
        CONSTRAINT CK_MUESTRA_RES_ESTADO CHECK (ESTADO IN ('PENDIENTE','CONFIRMADA','CANCELADA','FINALIZADA'))
      )
    ]';
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE <> -955 THEN RAISE; END IF;
  END;
END;
/

MERGE INTO PRENDA_MUESTRA target
USING (
  SELECT 'POLERA_BASICA' CODIGO_PRENDA, 'Polera básica' NOMBRE,
    'Polera cómoda para combinar en cualquier ocasión.' DESCRIPCION,
    'Poleras' CATEGORIA, 'M' TALLA, 'Unisex' GENERO, 10000 PRECIO_DIA, 20000 GARANTIA FROM DUAL
  UNION ALL
  SELECT 'CHALECO_TEJIDO', 'Chaleco tejido',
    'Chaleco abrigado de tejido suave para días fríos.',
    'Chalecos', 'S', 'Mujer', 10000, 20000 FROM DUAL
) source
ON (target.CODIGO_PRENDA = source.CODIGO_PRENDA)
WHEN MATCHED THEN UPDATE SET
  target.NOMBRE = source.NOMBRE,
  target.DESCRIPCION = source.DESCRIPCION,
  target.CATEGORIA = source.CATEGORIA,
  target.TALLA = source.TALLA,
  target.GENERO = source.GENERO,
  target.PRECIO_DIA = source.PRECIO_DIA,
  target.GARANTIA = source.GARANTIA
WHEN NOT MATCHED THEN INSERT
  (CODIGO_PRENDA, NOMBRE, DESCRIPCION, CATEGORIA, TALLA, GENERO, PRECIO_DIA, GARANTIA, ESTADO)
VALUES
  (source.CODIGO_PRENDA, source.NOMBRE, source.DESCRIPCION, source.CATEGORIA,
   source.TALLA, source.GENERO, source.PRECIO_DIA, source.GARANTIA, 'ACTIVA');

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX IX_MUESTRA_RES_FECHAS ON RESERVA_MUESTRA (CODIGO_PRENDA, ESTADO, FECHA_INICIO, FECHA_FIN)';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE <> -955 THEN RAISE; END IF;
END;
/

COMMIT;
