-- Procedimientos almacenados, funcion y triggers para las reservas de muestra de RentRoom.
-- Ejecutar como propietario del esquema RENTROOM_S5_EVIDENCE en XEPDB1, despues de
-- migrate_s8.sql y migrate_sample_reservations.sql. Se puede repetir sin perder datos.
SET SERVEROUTPUT ON
WHENEVER OSERROR EXIT FAILURE ROLLBACK
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
  current_schema VARCHAR2(128) := SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');
  container_name VARCHAR2(128) := SYS_CONTEXT('USERENV', 'CON_NAME');
BEGIN
  IF current_schema <> 'RENTROOM_S5_EVIDENCE' OR container_name <> 'XEPDB1' THEN
    RAISE_APPLICATION_ERROR(-20010, 'Seleccionar XEPDB1 y CURRENT_SCHEMA=RENTROOM_S5_EVIDENCE.');
  END IF;

  BEGIN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE AUDITORIA_RESERVA (
        ID_AUDITORIA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ID_RESERVA NUMBER NOT NULL,
        ACCION VARCHAR2(20) NOT NULL,
        ESTADO_ANTERIOR VARCHAR2(20),
        ESTADO_NUEVO VARCHAR2(20) NOT NULL,
        USUARIO_BD VARCHAR2(128) DEFAULT SYS_CONTEXT('USERENV', 'SESSION_USER') NOT NULL,
        FECHA_EVENTO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
      )
    ]';
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE <> -955 THEN RAISE; END IF;
  END;
END;
/

-- Calcula arriendo + garantia con los valores guardados en la reserva.
CREATE OR REPLACE FUNCTION FN_TOTAL_RESERVA_MUESTRA (
  P_ID_RESERVA IN NUMBER
) RETURN NUMBER AS
  V_TOTAL NUMBER;
BEGIN
  SELECT (TRUNC(FECHA_FIN) - TRUNC(FECHA_INICIO) + 1) * PRECIO_DIA + GARANTIA
    INTO V_TOTAL
    FROM RESERVA_MUESTRA
   WHERE ID_RESERVA = P_ID_RESERVA;
  RETURN V_TOTAL;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20002, 'La reserva indicada no existe.');
END;
/

-- Crea una reserva: bloquea la prenda, rechaza fechas superpuestas y toma tarifa y garantia vigentes.
CREATE OR REPLACE PROCEDURE SP_CREAR_RESERVA_MUESTRA (
  P_CODIGO_PRENDA   IN  VARCHAR2,
  P_ID_ARRENDATARIO IN  NUMBER,
  P_FECHA_INICIO    IN  DATE,
  P_FECHA_FIN       IN  DATE,
  P_ID_RESERVA      OUT NUMBER
) AS
  V_PRECIO_DIA NUMBER;
  V_GARANTIA   NUMBER;
  V_SUPERPUESTAS NUMBER;
BEGIN
  BEGIN
    SELECT PRECIO_DIA, GARANTIA INTO V_PRECIO_DIA, V_GARANTIA
      FROM PRENDA_MUESTRA
     WHERE CODIGO_PRENDA = P_CODIGO_PRENDA AND ESTADO = 'ACTIVA'
       FOR UPDATE;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RAISE_APPLICATION_ERROR(-20020, 'La prenda no esta disponible.');
  END;

  SELECT COUNT(*) INTO V_SUPERPUESTAS
    FROM RESERVA_MUESTRA
   WHERE CODIGO_PRENDA = P_CODIGO_PRENDA
     AND ESTADO IN ('PENDIENTE', 'CONFIRMADA')
     AND FECHA_INICIO <= P_FECHA_FIN
     AND FECHA_FIN >= P_FECHA_INICIO;
  IF V_SUPERPUESTAS > 0 THEN
    RAISE_APPLICATION_ERROR(-20021, 'La prenda ya esta reservada durante esas fechas.');
  END IF;

  INSERT INTO RESERVA_MUESTRA
    (CODIGO_PRENDA, ID_ARRENDATARIO, FECHA_INICIO, FECHA_FIN, PRECIO_DIA, GARANTIA, ESTADO)
  VALUES
    (P_CODIGO_PRENDA, P_ID_ARRENDATARIO, TRUNC(P_FECHA_INICIO), TRUNC(P_FECHA_FIN), V_PRECIO_DIA, V_GARANTIA, 'CONFIRMADA')
  RETURNING ID_RESERVA INTO P_ID_RESERVA;
END;
/

-- Cancela una reserva propia que aun no termino.
CREATE OR REPLACE PROCEDURE SP_CANCELAR_RESERVA_MUESTRA (
  P_ID_RESERVA      IN NUMBER,
  P_ID_ARRENDATARIO IN NUMBER
) AS
  V_ESTADO RESERVA_MUESTRA.ESTADO%TYPE;
BEGIN
  BEGIN
    SELECT ESTADO INTO V_ESTADO
      FROM RESERVA_MUESTRA
     WHERE ID_RESERVA = P_ID_RESERVA AND ID_ARRENDATARIO = P_ID_ARRENDATARIO
       FOR UPDATE;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RAISE_APPLICATION_ERROR(-20002, 'No existe una reserva tuya con ese identificador.');
  END;
  UPDATE RESERVA_MUESTRA SET ESTADO = 'CANCELADA' WHERE ID_RESERVA = P_ID_RESERVA;
END;
/

-- Valida fechas y transiciones de estado en cada reserva.
CREATE OR REPLACE TRIGGER TRG_RESERVA_MUESTRA_VALIDAR
BEFORE INSERT OR UPDATE OF FECHA_INICIO, FECHA_FIN, ESTADO ON RESERVA_MUESTRA
FOR EACH ROW
BEGIN
  IF :NEW.FECHA_FIN < :NEW.FECHA_INICIO THEN
    RAISE_APPLICATION_ERROR(-20001, 'La fecha de termino no puede ser anterior a la fecha de inicio.');
  END IF;
  IF INSERTING AND TRUNC(:NEW.FECHA_INICIO) < TRUNC(SYSDATE) THEN
    RAISE_APPLICATION_ERROR(-20003, 'La fecha de inicio no puede ser anterior a hoy.');
  END IF;
  IF UPDATING AND :OLD.ESTADO IN ('CANCELADA', 'FINALIZADA') AND :NEW.ESTADO <> :OLD.ESTADO THEN
    RAISE_APPLICATION_ERROR(-20004, 'Una reserva cancelada o finalizada no puede cambiar de estado.');
  END IF;
END;
/

-- Deja un registro de auditoria al crear una reserva o cambiar su estado.
CREATE OR REPLACE TRIGGER TRG_RESERVA_MUESTRA_AUDITORIA
AFTER INSERT OR UPDATE OF ESTADO ON RESERVA_MUESTRA
FOR EACH ROW
BEGIN
  IF INSERTING THEN
    INSERT INTO AUDITORIA_RESERVA (ID_RESERVA, ACCION, ESTADO_ANTERIOR, ESTADO_NUEVO)
    VALUES (:NEW.ID_RESERVA, 'CREAR', NULL, :NEW.ESTADO);
  ELSIF :OLD.ESTADO <> :NEW.ESTADO THEN
    INSERT INTO AUDITORIA_RESERVA (ID_RESERVA, ACCION, ESTADO_ANTERIOR, ESTADO_NUEVO)
    VALUES (:NEW.ID_RESERVA, 'CAMBIAR_ESTADO', :OLD.ESTADO, :NEW.ESTADO);
  END IF;
END;
/

-- Comprobacion: los objetos deben quedar VALID.
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS
  FROM USER_OBJECTS
 WHERE OBJECT_NAME IN ('FN_TOTAL_RESERVA_MUESTRA', 'SP_CREAR_RESERVA_MUESTRA', 'SP_CANCELAR_RESERVA_MUESTRA',
                       'TRG_RESERVA_MUESTRA_VALIDAR', 'TRG_RESERVA_MUESTRA_AUDITORIA')
 ORDER BY OBJECT_TYPE, OBJECT_NAME;
