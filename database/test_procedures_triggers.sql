-- Prueba manual de procedimientos y triggers. Ejecutar como propietario del esquema.
-- Todo se deshace al final (ROLLBACK), no deja datos.
SET SERVEROUTPUT ON
DECLARE
  V_USUARIO NUMBER;
  V_ID1 NUMBER;
  V_ID2 NUMBER;
  V_TOTAL NUMBER;
  V_INICIO DATE := TRUNC(SYSDATE) + 30;
BEGIN
  SELECT MIN(ID_USUARIO) INTO V_USUARIO FROM USUARIO WHERE ROL = 'CLIENTE';
  IF V_USUARIO IS NULL THEN
    RAISE_APPLICATION_ERROR(-20030, 'Crea primero una cuenta Cliente desde la aplicacion.');
  END IF;

  SP_CREAR_RESERVA_MUESTRA('POLERA_BASICA', V_USUARIO, V_INICIO, V_INICIO + 1, V_ID1);
  V_TOTAL := FN_TOTAL_RESERVA_MUESTRA(V_ID1);
  DBMS_OUTPUT.PUT_LINE('1) Reserva ' || V_ID1 || ' creada. Total esperado 40000, obtenido ' || V_TOTAL);

  BEGIN
    SP_CREAR_RESERVA_MUESTRA('POLERA_BASICA', V_USUARIO, V_INICIO + 1, V_INICIO + 2, V_ID2);
    DBMS_OUTPUT.PUT_LINE('2) ERROR: acepto fechas superpuestas');
  EXCEPTION WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('2) Superposicion rechazada: ' || SQLERRM);
  END;

  SP_CANCELAR_RESERVA_MUESTRA(V_ID1, V_USUARIO);
  BEGIN
    UPDATE RESERVA_MUESTRA SET ESTADO = 'CONFIRMADA' WHERE ID_RESERVA = V_ID1;
    DBMS_OUTPUT.PUT_LINE('3) ERROR: reactivo una reserva cancelada');
  EXCEPTION WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('3) Trigger de estado: ' || SQLERRM);
  END;

  FOR A IN (SELECT ACCION, ESTADO_ANTERIOR, ESTADO_NUEVO FROM AUDITORIA_RESERVA WHERE ID_RESERVA = V_ID1 ORDER BY ID_AUDITORIA) LOOP
    DBMS_OUTPUT.PUT_LINE('4) Auditoria: ' || A.ACCION || ' ' || NVL(A.ESTADO_ANTERIOR, '-') || ' -> ' || A.ESTADO_NUEVO);
  END LOOP;
  ROLLBACK;
END;
/
