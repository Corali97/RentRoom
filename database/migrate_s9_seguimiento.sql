-- RentRoom S9: seguimiento de entrega, devolución, daño y garantía.
-- Ejecutar una sola vez después de migrate_s9_reservas.sql; respaldar antes.
-- La tabla guarda estado informativo: no mueve dinero.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
CREATE TABLE SEGUIMIENTO_ARRIENDO (
 ID_RESERVA NUMBER PRIMARY KEY REFERENCES RESERVA(ID_RESERVA),
 FECHA_ENTREGA TIMESTAMP,
 FECHA_DEVOLUCION TIMESTAMP,
 OBSERVACION_DANOS VARCHAR2(500),
 ESTADO_GARANTIA VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
 CONSTRAINT CK_SEGUIMIENTO_GARANTIA CHECK (ESTADO_GARANTIA IN ('PENDIENTE','LIBERADA','RETENIDA'))
);
CREATE TABLE HISTORIAL_ARRIENDO (
 ID_EVENTO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ID_RESERVA NUMBER NOT NULL REFERENCES RESERVA(ID_RESERVA),
 ID_ACTOR NUMBER NOT NULL REFERENCES USUARIO(ID_USUARIO),
 ACCION VARCHAR2(30) NOT NULL,
 DETALLE VARCHAR2(500),
 FECHA_EVENTO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE OR REPLACE PROCEDURE SP_GESTIONAR_ARRIENDO (
 P_ID_RESERVA IN NUMBER, P_ID_PROPIETARIO IN NUMBER,
 P_ACCION IN VARCHAR2, P_DETALLE IN VARCHAR2 DEFAULT NULL
) AS
 V_ID_PRODUCTO NUMBER; V_PROPIETARIO NUMBER; V_ESTADO VARCHAR2(20);
 V_ENTREGA TIMESTAMP; V_DEVOLUCION TIMESTAMP;
BEGIN
 IF P_ACCION NOT IN ('ENTREGAR','DEVOLVER','DANO','LIBERAR_GARANTIA','RETENER_GARANTIA') THEN
  RAISE_APPLICATION_ERROR(-20201,'Accion no valida.'); END IF;
 IF LENGTH(P_DETALLE)>500 THEN RAISE_APPLICATION_ERROR(-20202,'Detalle demasiado largo.'); END IF;
 SELECT ID_PRODUCTO INTO V_ID_PRODUCTO FROM RESERVA WHERE ID_RESERVA=P_ID_RESERVA;
 SELECT ID_PROPIETARIO INTO V_PROPIETARIO FROM PRODUCTO WHERE ID_PRODUCTO=V_ID_PRODUCTO FOR UPDATE;
 IF V_PROPIETARIO<>P_ID_PROPIETARIO THEN RAISE_APPLICATION_ERROR(-20203,'Propietario no autorizado.'); END IF;
 SELECT ESTADO INTO V_ESTADO FROM RESERVA WHERE ID_RESERVA=P_ID_RESERVA FOR UPDATE;
 IF V_ESTADO NOT IN ('CONFIRMADA','FINALIZADA') THEN
  RAISE_APPLICATION_ERROR(-20204,'La reserva no esta confirmada.'); END IF;
 MERGE INTO SEGUIMIENTO_ARRIENDO S USING(SELECT P_ID_RESERVA AS ID_RESERVA FROM DUAL) D
 ON(S.ID_RESERVA=D.ID_RESERVA)
 WHEN NOT MATCHED THEN INSERT(ID_RESERVA) VALUES(D.ID_RESERVA);
 SELECT FECHA_ENTREGA,FECHA_DEVOLUCION INTO V_ENTREGA,V_DEVOLUCION FROM SEGUIMIENTO_ARRIENDO
 WHERE ID_RESERVA=P_ID_RESERVA FOR UPDATE;
 IF P_ACCION='ENTREGAR' THEN
  IF V_ESTADO<>'CONFIRMADA' OR V_ENTREGA IS NOT NULL THEN RAISE_APPLICATION_ERROR(-20205,'Entrega no permitida.'); END IF;
  UPDATE SEGUIMIENTO_ARRIENDO SET FECHA_ENTREGA=SYSTIMESTAMP WHERE ID_RESERVA=P_ID_RESERVA;
 ELSIF P_ACCION='DEVOLVER' THEN
  IF V_ESTADO<>'CONFIRMADA' OR V_ENTREGA IS NULL OR V_DEVOLUCION IS NOT NULL THEN
   RAISE_APPLICATION_ERROR(-20206,'Devolucion no permitida.'); END IF;
  UPDATE SEGUIMIENTO_ARRIENDO SET FECHA_DEVOLUCION=SYSTIMESTAMP WHERE ID_RESERVA=P_ID_RESERVA;
  UPDATE RESERVA SET ESTADO='FINALIZADA' WHERE ID_RESERVA=P_ID_RESERVA;
 ELSIF P_ACCION='DANO' THEN
  IF V_ENTREGA IS NULL OR P_DETALLE IS NULL OR TRIM(P_DETALLE) IS NULL THEN
   RAISE_APPLICATION_ERROR(-20207,'Describe el dano despues de entregar.'); END IF;
  UPDATE SEGUIMIENTO_ARRIENDO SET OBSERVACION_DANOS=P_DETALLE WHERE ID_RESERVA=P_ID_RESERVA;
 ELSE
  IF V_DEVOLUCION IS NULL THEN RAISE_APPLICATION_ERROR(-20208,'Primero registra la devolucion.'); END IF;
  UPDATE SEGUIMIENTO_ARRIENDO SET ESTADO_GARANTIA=
  CASE WHEN P_ACCION='LIBERAR_GARANTIA' THEN 'LIBERADA' ELSE 'RETENIDA' END
  WHERE ID_RESERVA=P_ID_RESERVA;
 END IF;
 INSERT INTO HISTORIAL_ARRIENDO(ID_RESERVA,ID_ACTOR,ACCION,DETALLE)
 VALUES(P_ID_RESERVA,P_ID_PROPIETARIO,P_ACCION,P_DETALLE);
EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20209,'Reserva inexistente.');
END;
/
-- Evitar cancelar una reserva después de que el producto haya sido entregado.
CREATE OR REPLACE PROCEDURE SP_CANCELAR_RESERVA(P_ID_RESERVA IN NUMBER,P_ID_CLIENTE IN NUMBER) AS
 V_PRODUCTO NUMBER; V_ESTADO RESERVA.ESTADO%TYPE; V_LOCK NUMBER; V_ENTREGAS NUMBER;
BEGIN
 SELECT ID_PRODUCTO INTO V_PRODUCTO FROM RESERVA WHERE ID_RESERVA=P_ID_RESERVA;
 SELECT ID_PRODUCTO INTO V_LOCK FROM PRODUCTO WHERE ID_PRODUCTO=V_PRODUCTO FOR UPDATE;
 SELECT ESTADO INTO V_ESTADO FROM RESERVA WHERE ID_RESERVA=P_ID_RESERVA AND ID_ARRENDATARIO=P_ID_CLIENTE FOR UPDATE;
 IF V_ESTADO NOT IN ('PENDIENTE','CONFIRMADA') THEN RAISE_APPLICATION_ERROR(-20106,'Reserva no cancelable.'); END IF;
 SELECT COUNT(*) INTO V_ENTREGAS FROM SEGUIMIENTO_ARRIENDO WHERE ID_RESERVA=P_ID_RESERVA AND FECHA_ENTREGA IS NOT NULL;
 IF V_ENTREGAS>0 THEN RAISE_APPLICATION_ERROR(-20210,'No se cancela un arriendo entregado.'); END IF;
 UPDATE RESERVA SET ESTADO='CANCELADA' WHERE ID_RESERVA=P_ID_RESERVA;
EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20107,'Reserva ajena o inexistente.');
END;
/
SELECT OBJECT_NAME,STATUS FROM USER_OBJECTS WHERE OBJECT_NAME IN ('SP_GESTIONAR_ARRIENDO','SP_CANCELAR_RESERVA');
