-- RentRoom - avance de modelo de datos Semana 5
-- Esquema relacional inicial alineado con usuarios, productos y reservas.

CREATE TABLE USUARIO (
  ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOMBRE_COMPLETO VARCHAR2(120) NOT NULL,
  CORREO VARCHAR2(150) NOT NULL UNIQUE,
  CLAVE_HASH VARCHAR2(255) NOT NULL,
  FECHA_REGISTRO DATE DEFAULT SYSDATE NOT NULL,
  ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
  CONSTRAINT CK_USUARIO_ESTADO CHECK (ESTADO IN ('ACTIVO','INACTIVO'))
);

CREATE TABLE PRODUCTO (
  ID_PRODUCTO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_PROPIETARIO NUMBER NOT NULL,
  NOMBRE VARCHAR2(120) NOT NULL,
  DESCRIPCION VARCHAR2(500),
  CATEGORIA VARCHAR2(80),
  PRECIO_DIA NUMBER(10,2) NOT NULL,
  GARANTIA NUMBER(10,2) DEFAULT 0 NOT NULL,
  ESTADO VARCHAR2(20) DEFAULT 'DISPONIBLE' NOT NULL,
  CONSTRAINT FK_PRODUCTO_USUARIO FOREIGN KEY (ID_PROPIETARIO) REFERENCES USUARIO(ID_USUARIO),
  CONSTRAINT CK_PRODUCTO_PRECIO CHECK (PRECIO_DIA >= 0),
  CONSTRAINT CK_PRODUCTO_GARANTIA CHECK (GARANTIA >= 0),
  CONSTRAINT CK_PRODUCTO_ESTADO CHECK (ESTADO IN ('DISPONIBLE','RESERVADO','INACTIVO'))
);

CREATE TABLE RESERVA (
  ID_RESERVA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_PRODUCTO NUMBER NOT NULL,
  ID_ARRENDATARIO NUMBER NOT NULL,
  FECHA_INICIO DATE NOT NULL,
  FECHA_FIN DATE NOT NULL,
  ESTADO VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
  FECHA_CREACION DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT FK_RESERVA_PRODUCTO FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTO(ID_PRODUCTO),
  CONSTRAINT FK_RESERVA_USUARIO FOREIGN KEY (ID_ARRENDATARIO) REFERENCES USUARIO(ID_USUARIO),
  CONSTRAINT CK_RESERVA_FECHAS CHECK (FECHA_FIN >= FECHA_INICIO),
  CONSTRAINT CK_RESERVA_ESTADO CHECK (ESTADO IN ('PENDIENTE','CONFIRMADA','CANCELADA','FINALIZADA'))
);

CREATE OR REPLACE PROCEDURE SP_ACTUALIZAR_ESTADO_RESERVA (
  P_ID_RESERVA IN NUMBER,
  P_ESTADO IN VARCHAR2
) AS
BEGIN
  UPDATE RESERVA
     SET ESTADO = UPPER(P_ESTADO)
   WHERE ID_RESERVA = P_ID_RESERVA;
  IF SQL%ROWCOUNT = 0 THEN
    RAISE_APPLICATION_ERROR(-20002, 'La reserva indicada no existe.');
  END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_VALIDAR_RESERVA
BEFORE INSERT OR UPDATE OF FECHA_INICIO, FECHA_FIN ON RESERVA
FOR EACH ROW
BEGIN
  IF :NEW.FECHA_FIN < :NEW.FECHA_INICIO THEN
    RAISE_APPLICATION_ERROR(-20001, 'La fecha de término no puede ser anterior a la fecha de inicio.');
  END IF;
END;
/
